    for c in result['courses']:
        lines+=['',f'## {c["name"]}', '']
        for kind,label in [('required','建议先具备'),('recommended','可并行补充')]:
            lines.append(label+'：'+'、'.join(names[e['before_id']] for e in result['course_edges'] if e['after_id']==c['id'] and e['kind']==kind) if any(e['after_id']==c['id'] and e['kind']==kind for e in result['course_edges']) else label+'：无目录内整课要求')
        for ch in c['chapters']:lines.append(f'- 第{ch["position"]}章 {ch["title"]}：'+ '、'.join(skill_names[s]+'（'+s+'）' for s in ch['skill_ids']))
        lines+=['','知识点先修（箭头左侧为基础，右侧为后续知识）：','']
        course_skills={s for ch in c['chapters'] for s in ch['skill_ids']}
        for e in result['skill_edges']:
            if e['after_id'] in course_skills:lines.append('- '+skill_names[e['before_id']]+' → '+skill_names[e['after_id']])
        external=[e['name'] for e in result['external_requirements'] if e['course_id']==c['id']]
        if external:lines.append('目录外基础：'+'、'.join(external))
    lines+=['','## 参考资料','']+[f'- [{r["id"]}]({r["url"]})：{r["use"]}' for r in result['references']]
    (BASE/'curriculum-relations.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps({k:len(result[k]) for k in ['courses','course_edges','skill_edges','chapter_edges','external_requirements']}))
