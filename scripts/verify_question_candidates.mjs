import {chromium,expect} from '../frontend/node_modules/@playwright/test/index.mjs';
import {readFile} from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const credentials=await readFile('backend/data/initial-accounts.txt','utf8');
 const line=credentials.split(/\r?\n/).find(x=>x.trim().startsWith('admin:'));
 if(!line)throw new Error('Administrator record unavailable; no password printed');
 const password=line.split(':').slice(1).join(':').trim().split(/\s/)[0];
 await page.goto('http://127.0.0.1:8000/');
 await page.getByLabel('账号',{exact:true}).fill('admin');
 await page.getByLabel('密码',{exact:true}).fill(password);
 await page.getByRole('button',{name:'登录',exact:true}).click();
 await page.locator('nav a[href="#publish"]').click();
 await expect(page.getByRole('heading',{name:'专业课程与中文资料导读'})).toBeVisible();
 const selector=page.getByLabel('选择专业课程',{exact:true});
 await expect(selector.locator('option')).toHaveCount(36);
 await selector.selectOption('public-C03');
 const catalog=page.locator('section.card').filter({has:page.getByRole('heading',{name:'专业课程与中文资料导读'})});
 await catalog.getByRole('button',{name:'阅读中文导读'}).first().click();
 await expect(page.locator('article.reading')).toContainText('中文资料导读');
 await expect(page.locator('article.reading')).toContainText('数据结构');
 await expect(page.getByRole('link',{name:'打开外部网址 ↗（正文未验证）'})).toHaveAttribute('href',/https:\/\/ocw.mit.edu\//);
 await page.screenshot({path:'docs/evidence/implementation/public-catalog-browser.png',fullPage:true});
 expect(errors).toEqual([]);
 await page.locator('nav a[href="#graphs"]').click();
 await expect(page.getByRole('heading',{name:'公开试题与答案 · 待审核题库'})).toBeVisible();
 await expect(page.getByText('37个题组来源 · 15条中文题答摘要 · 正式发布0题',{exact:true})).toBeVisible();
 await page.screenshot({path:'docs/evidence/implementation/question-candidates-browser.png',fullPage:true});
 await page.getByRole('button',{name:'退出登录',exact:true}).click();
 console.log(JSON.stringify({courses:36,chineseGuideVisible:true,originalLinkPreserved:true,errors}));
}finally{await browser.close();}
