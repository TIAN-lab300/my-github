import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const context=await browser.newContext({permissions:['clipboard-read','clipboard-write']});
const page=await context.newPage(),base='http://127.0.0.1:8003';
const results=[];
page.on('dialog',d=>d.accept());
try{
 await page.goto(base);
 await page.getByLabel('账号',{exact:true}).fill('teacher');
 await page.getByLabel('密码',{exact:true}).fill('AcceptanceOnly!123');
 await page.getByRole('button',{name:'登录',exact:true}).click();
 await page.getByRole('button',{name:'退出登录'}).waitFor();
 const created=await context.request.post(base+'/api/v1/classes',{data:{name:'复制与链接验收-'+Date.now(),description:'独立数据'}});
 const cid=(await created.json()).id;
 await page.reload();
 await page.locator('select:not([name])').first().selectOption(cid);
 await page.locator('input[name=hours]').fill('6');
 await page.locator('input[name=uses]').fill('3');
 const response=page.waitForResponse(r=>r.url().endsWith('/invites')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'生成自定义邀请码'}).click();
 const invitation=await (await response).json();
 await page.getByRole('button',{name:'复制邀请码'}).click();
 assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),invitation.code);
 const invitations=await (await context.request.get(base+'/api/v1/classes/'+cid+'/invites')).json();
 const stored=invitations.find(i=>i.id===invitation.id);
 assert.equal(stored.max_uses,3);
 const hours=(Date.parse(stored.expires_at)-Date.now())/3600000;
 assert(hours>5.9&&hours<=6);
 results.push({id:'SF-CLASS-03',status:'passed',actual:'页面设置6小时/3次，服务端状态一致，剪贴板原码逐字相等'});
 await page.getByRole('link',{name:'课程知识库'}).click();
 const form=page.locator('form').filter({has:page.locator('input[name=url]')});
 await form.locator('select').selectOption(cid);
 const title='登记链接-'+Date.now();
 await form.locator('input[name=title]').fill(title);
 await page.getByLabel('HTTP/HTTPS网址').fill('https://example.com/course');
 await page.getByLabel('推荐理由').fill('教师审核过的推荐入口');
 await page.getByRole('button',{name:'保存待审核链接'}).click();
 const card=page.locator('section.card').filter({has:page.getByRole('heading',{name:title,exact:true})});
 await card.getByRole('button',{name:'发布',exact:true}).click();
 await card.getByRole('button',{name:'下架',exact:true}).waitFor();
 await card.getByRole('button',{name:'查看资料'}).click();
 const link=page.getByRole('link',{name:'打开外部网址 ↗（正文未验证）'});
 assert.equal(await link.getAttribute('href'),'https://example.com/course');
 results.push({id:'SF-RESOURCE-11',status:'passed',actual:'页面登记、待审核草稿及发布成功，外链显示正文未验证'});
 await page.screenshot({path:'../docs/evidence/implementation/batch2-link-review.png',fullPage:true});
}catch(e){results.push({id:'FLOW',status:'failed',error:e.message})}
finally{await browser.close();fs.writeFileSync('../docs/evidence/implementation/batch2-copy-link.json',JSON.stringify({checked_at:new Date().toISOString(),results},null,2))}
console.log(JSON.stringify(results,null,2));
